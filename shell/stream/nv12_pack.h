// НаомиФон — кадр RGBA → NV12 в раскладке видеокодера, на видеочипе, одним проходом. Цель — буфер RGBA, который
// кодер читает как сплошные байты: каждый его пиксель несёт 4 байта NV12 — четыре яркости или две пары цветности
// (U, V). Строка буфера (pitch) может быть любой: gralloc иногда выравнивает её по-своему (для 1920 × 1080 — 768
// пикселей вместо 512), поэтому шейдер считает место каждого байта в памяти, а не в строке NV12; ширина буфера должна
// быть равна его строке (grallocAllocateLinear) — иначе хвост строки текстуре не виден. В раскладке NV12
// строки 0…h−1 — яркость, с yScan — цветность (h/2 строк), остальное — выравнивание (docs/STREAM.md).
// Цвет — BT.709, узкий диапазон (16…235), как ждёт декодер.
//   Обычный случай — строка буфера равна строке NV12 (pitch × 4 = nvStride): строка цели — это строка NV12, и место
//   байта считать не нужно. Тогда — два прохода по своим областям (яркость, цветность) простыми шейдерами: без
//   целочисленного деления и ветвлений в каждой точке и без точек выравнивания; перед ними цель объявляется пустой
//   (glInvalidateFramebuffer) — видеочипу незачем подгружать её прежнее содержимое. Выравнивание кодер не читает;
//   каждый буфер один раз чистится целиком. NAOMI_STREAM_PACK=old — прежний общий шейдер (для сравнения)
#pragma once

#include <GLES3/gl3.h>

#include <cstddef>
#include <vector>

class Nv12Packer
{
public:
    // w × h — кадр потока; nvStride (байт), yScan, size — раскладка NV12 кодера; pitch — строка буфера-цели, пикселей RGBA
    bool init(int w, int h, int nvStride, int yScan, size_t size, int pitch, int rotation = 0);
    // src — текстура RGBA любого размера (растягивается под кадр); flipY — у src первая строка внизу
    // (кадр окна GL); dstFbo — кадровый буфер цели
    void pack(GLuint src, bool flipY, GLuint dstFbo);
    void release();

private:
    GLuint m_program = 0;
    GLuint m_vao = 0;
    GLint m_uFlip = -1;
    int m_pitch = 0, m_rows = 0;
    // быстрый путь: два шейдера по областям
    GLuint m_luma = 0, m_chroma = 0;
    GLint m_lumaFlip = -1, m_chromaFlip = -1;
    int m_w = 0, m_h = 0, m_yScan = 0;
    std::vector<GLuint> m_cleared;   // буферы-цели, уже очищенные целиком
};
